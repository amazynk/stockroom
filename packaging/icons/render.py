"""Draws Stockroom's icon and exports every size the three systems use.

The icon is amazynk.com's mark (a circled A, with the signal-orange square of the site's
favicon) on the family's squircle in ink, over the ruler that runs under the window's
header. The squircle is the one Specular, Dozed and Pagebara share: a superellipse with
exponent 5, 824 units wide on a 1024 grid (the macOS keyline).

Writes, next to this file:
  stockroom.svg            the icon (1024 grid)
  stockroom-small.svg      the same mark for 16 to 48 px: a fuller tile, heavier lines, no ruler
  suite-<size>.png     16, 24, 32, 48 (small) and 64, 128, 256, 512, 1024
  stockroom.icns           macOS (iconutil; only on a Mac)
  stockroom.ico            Windows: 16, 24, 32, 48, 64, 128, 256, each stored as PNG

Needs resvg, and iconutil for the .icns; run `sh render.sh`.
"""

import math
import shutil
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent

INK = "#111111"
INK_TOP = "#2a2a2a"
BONE = "#ebe9e3"
SIGNAL = "#ff4d0a"

SMALL = (16, 24, 32, 48)
LARGE = (64, 128, 256, 512, 1024)


def squircle(cx, cy, a, n=5.0, steps=720):
    """The family's tile outline: |x|^n + |y|^n = a^n, as a closed path."""
    pts = []
    for i in range(steps):
        t = 2 * math.pi * i / steps
        c, s = math.cos(t), math.sin(t)
        x = cx + a * math.copysign(abs(c) ** (2 / n), c)
        y = cy + a * math.copysign(abs(s) ** (2 / n), s)
        pts.append(f"{x:.2f} {y:.2f}")
    return "M " + " L ".join(pts) + " Z"


def mark(cx, cy, r, ring, stem):
    """The circled A of amazynk.com (the favicon's geometry, scaled so the ring has radius r)."""
    k = r / 22
    apex = (cx, cy - 13 * k)
    left, right = (cx - 10.5 * k, cy + 11 * k), (cx + 10.5 * k, cy + 11 * k)
    bar_y, bar_x = cy + 3 * k, 6.6 * k
    return (
        f'<circle cx="{cx:.1f}" cy="{cy:.1f}" r="{r:.1f}" fill="none" stroke="{BONE}" '
        f'stroke-width="{ring:.1f}"/>\n'
        f'  <path d="M {left[0]:.1f} {left[1]:.1f} L {apex[0]:.1f} {apex[1]:.1f} '
        f'L {right[0]:.1f} {right[1]:.1f} M {cx - bar_x:.1f} {bar_y:.1f} H {cx + bar_x:.1f}" '
        f'fill="none" stroke="{BONE}" stroke-width="{stem:.1f}" stroke-miterlimit="8"/>'
    )


def ruler(left, right, base, step, short, tall):
    """Ticks along a baseline: every `step`, a tall one every fifth, as under the header."""
    count = int((right - left) // step)
    left = (left + right - count * step) / 2
    ticks = []
    for i in range(count + 1):
        x = left + i * step
        h = tall if i % 5 == 0 else short
        ticks.append(f"M {x:.1f} {base:.1f} V {base - h:.1f}")
    line = f"M {left:.1f} {base:.1f} H {left + count * step:.1f}"
    return (
        f'<path d="{line} {" ".join(ticks)}" fill="none" stroke="{BONE}" '
        f'stroke-opacity="0.55" stroke-width="5"/>'
    )


def icon_svg():
    body = squircle(512, 512, 412)
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- Stockroom's icon. Generated by packaging/icons/render.py; edit that, not this. -->
<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
  <title>Stockroom</title>
  <defs>
    <linearGradient id="body" x1="0" y1="100" x2="0" y2="924" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="{INK_TOP}"/>
      <stop offset="0.6" stop-color="{INK}"/>
    </linearGradient>
    <linearGradient id="rim" x1="0" y1="100" x2="0" y2="512" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#ffffff" stop-opacity="0.16"/>
      <stop offset="1" stop-color="#ffffff" stop-opacity="0"/>
    </linearGradient>
    <clipPath id="tile"><path d="{body}"/></clipPath>
  </defs>
  <path d="{body}" fill="url(#body)"/>
  <path d="{body}" fill="none" stroke="url(#rim)" stroke-width="6" clip-path="url(#tile)"/>
  {mark(512, 470, 236, 36, 40)}
  <rect x="728" y="196" width="76" height="76" fill="{SIGNAL}"/>
  {ruler(212, 812, 812, 24, 20, 44)}
</svg>
"""


def small_svg():
    body = squircle(512, 512, 488)
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- Stockroom's icon for 16 to 48 px. Generated by packaging/icons/render.py. -->
<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
  <title>Stockroom</title>
  <path d="{body}" fill="{INK}"/>
  {mark(500, 530, 330, 80, 88)}
  <rect x="760" y="104" width="148" height="148" fill="{SIGNAL}"/>
</svg>
"""


def render(svg, size, dest):
    subprocess.run(["resvg", "-w", str(size), "-h", str(size), str(svg), str(dest)], check=True)


def write_ico(pngs, dest):
    """An .ico whose entries are the PNG files as they are (Windows Vista and later read
    these), so the 256 px entry is a few kilobytes and not a 256 KB bitmap."""
    blobs = [p.read_bytes() for p in pngs]
    header = struct.pack("<HHH", 0, 1, len(blobs))
    offset = len(header) + 16 * len(blobs)
    entries = b""
    for blob in blobs:
        width, height = struct.unpack(">II", blob[16:24])
        entries += struct.pack(
            "<BBBBHHII", width % 256, height % 256, 0, 0, 1, 32, len(blob), offset
        )
        offset += len(blob)
    dest.write_bytes(header + entries + b"".join(blobs))


def main():
    if not shutil.which("resvg"):
        sys.exit("render.py needs resvg")
    (HERE / "stockroom.svg").write_text(icon_svg(), encoding="utf-8")
    (HERE / "stockroom-small.svg").write_text(small_svg(), encoding="utf-8")
    pngs = {}
    for size in SMALL:
        pngs[size] = HERE / f"stockroom-{size}.png"
        render(HERE / "stockroom-small.svg", size, pngs[size])
    for size in LARGE:
        pngs[size] = HERE / f"stockroom-{size}.png"
        render(HERE / "stockroom.svg", size, pngs[size])
    if shutil.which("iconutil"):
        with tempfile.TemporaryDirectory() as tmp:
            iconset = Path(tmp) / "stockroom.iconset"
            iconset.mkdir()
            for size in (16, 32, 128, 256, 512):
                source = "stockroom-small.svg" if size in SMALL else "stockroom.svg"
                render(HERE / source, size, iconset / f"icon_{size}x{size}.png")
                double = size * 2
                source = "stockroom-small.svg" if double in SMALL else "stockroom.svg"
                render(HERE / source, double, iconset / f"icon_{size}x{size}@2x.png")
            subprocess.run(["iconutil", "-c", "icns", str(iconset), "-o", str(HERE / "stockroom.icns")], check=True)
    else:
        print("no iconutil (not a Mac): stockroom.icns left as it was")
    write_ico([pngs[s] for s in (16, 24, 32, 48, 64, 128, 256)], HERE / "stockroom.ico")


if __name__ == "__main__":
    main()
